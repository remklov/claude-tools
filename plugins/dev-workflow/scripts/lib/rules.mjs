// Rules engine: parses rule files, layers core → packs → project, resolves scopes and writes the
// compiled rulebook into .claude/rules/workflow/ with a lock file (spec 03).
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';
import { matchAny } from './glob.mjs';
import { CwError, warn } from './out.mjs';
import { pluginVersion } from './paths.mjs';
import { withPackOptions } from './packs.mjs';
import { render } from './template.mjs';
import { readJson, writeAtomic, writeJson } from './fsx.mjs';

export const GENERATED_MARKER = '<!-- Generated by dev-workflow (cw rules build). Do not edit. -->';
const HEADING = /^## ([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)+) (?:—|-) (.+)$/;
const META = /^<!--\s*rule:\s*(.*?)\s*-->$/;

const sha = (text) => `sha256:${createHash('sha256').update(text).digest('hex').slice(0, 16)}`;

export function parseRuleFile(text, source) {
  const lines = text.replace(/^---\n[\s\S]*?\n---\n/, '').split('\n');
  const rules = [];
  let current = null;
  for (let i = 0; i < lines.length; i += 1) {
    const heading = HEADING.exec(lines[i]);
    if (heading) {
      if (current) rules.push(current);
      const meta = META.exec((lines[i + 1] ?? '').trim());
      if (!meta) throw new CwError(`${source}: rule ${heading[1]} has no "<!-- rule: … -->" line under its heading`);
      const fields = Object.fromEntries(meta[1].split(';').map((part) => part.trim()).filter(Boolean).map((part) => {
        const eq = part.indexOf('=');
        return [part.slice(0, eq).trim(), part.slice(eq + 1).trim()];
      }));
      current = {
        id: heading[1],
        title: heading[2].trim(),
        severity: fields.severity ?? 'blocking',
        scope: fields.scope ?? 'all',
        protected: fields.protected === 'true',
        aliases: fields.aliases ? fields.aliases.split(',').map((alias) => alias.trim()) : [],
        when: fields.when ?? null,
        body: [],
        source,
      };
      i += 1;
      continue;
    }
    if (current) current.body.push(lines[i]);
  }
  if (current) rules.push(current);
  return rules.map((rule) => ({ ...rule, body: rule.body.join('\n').trim() }));
}

function resolvePlaceholders(text, values, where) {
  const resolved = render(text, values);
  const left = /\{(options|ruleOptions|project)\.[a-zA-Z.]+\}/.exec(resolved);
  if (left) throw new CwError(`${where}: unresolved placeholder ${left[0]}`);
  return resolved;
}

// `when=option:<name>` keeps a rule only if that pack option is truthy (or equals a value: option:<name>=<value>).
function ruleIsActive(rule, pack) {
  if (!rule.when) return true;
  const match = /^option:([a-zA-Z]+)(?:=(.+))?$/.exec(rule.when);
  if (!match) return true;
  const value = pack?.options?.[match[1]];
  return match[2] === undefined ? Boolean(value) : String(value) === match[2];
}

export function collectRules(ctx, profile, packs) {
  const byId = new Map();
  const add = (rule, layer) => {
    const existing = byId.get(rule.id);
    if (existing && existing.layerSource !== rule.layerSource) {
      throw new CwError(`Duplicate rule ID ${rule.id} in ${existing.source} and ${rule.source}`);
    }
    byId.set(rule.id, { ...rule, layer });
  };
  packs.forEach((pack, layer) => {
    const files = [];
    if (pack.manifest.rules) files.push(pack.manifest.rules);
    if (pack.variant && pack.manifest.variants?.[pack.variant]?.rules) files.push(pack.manifest.variants[pack.variant].rules);
    for (const file of files) {
      const path = join(pack.root, file);
      for (const rule of parseRuleFile(readFileSync(path, 'utf8'), `${pack.id}${pack.variant ? `@${pack.variant}` : ''}`)) {
        if (!ruleIsActive(rule, pack)) {
          byId.delete(rule.id);
          continue;
        }
        const values = { options: {}, ruleOptions: profile.rules.options[rule.id] ?? {}, project: profile.project };
        for (const [key, value] of Object.entries(pack.options)) values.options[key] = Array.isArray(value) ? value.join(', ') : value;
        add({
          ...rule,
          layerSource: pack.id,
          pack: pack.id,
          body: resolvePlaceholders(rule.body, values, `${pack.id}/${rule.id}`),
          scope: withPackOptions(rule.scope, pack),
        }, layer);
      }
    }
  });
  const projectLayer = packs.length;
  for (const file of profile.rules.add) {
    const path = join(ctx.configRoot ?? ctx.repoRoot, file);
    if (!existsSync(path)) throw new CwError(`rules.add: ${file} does not exist`);
    for (const rule of parseRuleFile(readFileSync(path, 'utf8'), file)) {
      if (byId.has(rule.id)) throw new CwError(`Duplicate rule ID ${rule.id} in ${byId.get(rule.id).source} and ${file}`);
      const values = { ruleOptions: profile.rules.options[rule.id] ?? {}, project: profile.project, options: {} };
      add({ ...rule, layerSource: 'project', pack: 'project', body: resolvePlaceholders(rule.body, values, `${file}/${rule.id}`) }, projectLayer);
    }
  }
  return byId;
}

export function applyCustomizations(ctx, profile, byId) {
  const errors = [];
  const protectedAllowed = profile.rules.allowProtected === true;
  for (const [id, file] of Object.entries(profile.rules.override)) {
    const rule = byId.get(id);
    if (!rule) { errors.push(`rules.override: unknown rule ${id}`); continue; }
    if (rule.protected && !protectedAllowed) { errors.push(`rules.override: ${id} is protected (needs allowProtected)`); continue; }
    const text = readFileSync(join(ctx.configRoot ?? ctx.repoRoot, file), 'utf8');
    const parsed = HEADING.test(text.split('\n').find((line) => line.startsWith('## ')) ?? '') ? parseRuleFile(text, file).find((r) => r.id === id) : null;
    byId.set(id, parsed ? { ...rule, ...parsed, layer: rule.layer, pack: rule.pack, modified: 'override' } : { ...rule, body: text.trim(), modified: 'override' });
  }
  for (const [id, text] of Object.entries(profile.rules.extend)) {
    const rule = byId.get(id);
    if (!rule) { errors.push(`rules.extend: unknown rule ${id}`); continue; }
    byId.set(id, { ...rule, body: `${rule.body}\n\n**Project addition:** ${text}`, modified: rule.modified ?? 'extend' });
  }
  const disabled = [];
  for (const { id, reason } of profile.rules.disable) {
    const rule = byId.get(id);
    if (!rule) { errors.push(`rules.disable: unknown rule ${id}`); continue; }
    if (rule.protected && !protectedAllowed) { errors.push(`rules.disable: ${id} is protected (needs allowProtected)`); continue; }
    byId.delete(id);
    disabled.push({ id, reason });
  }
  for (const id of Object.keys(profile.rules.options)) if (!byId.has(id) && !disabled.some((d) => d.id === id)) errors.push(`rules.options: unknown rule ${id}`);
  for (const [alias, targets] of Object.entries(profile.rules.aliases ?? {})) {
    for (const id of [].concat(targets)) {
      const rule = byId.get(id);
      if (!rule) { errors.push(`rules.aliases: ${alias} points to unknown rule ${id}`); continue; }
      byId.set(id, { ...rule, aliases: [...new Set([...rule.aliases, alias.toUpperCase()])] });
    }
  }
  if (errors.length) throw new CwError(`Rule customization failed:\n${errors.join('\n')}`);
  return disabled;
}

export function resolveScope(profile, scope) {
  if (scope === 'all') return { kind: 'global', globs: [], areas: [] };
  if (scope.startsWith('areas:')) {
    const areas = scope.slice(6).split(',').map((area) => area.trim()).filter(Boolean);
    const globs = [];
    for (const pkg of profile.packages) {
      if (!pkg.areas.some((area) => areas.includes(area))) continue;
      for (const path of pkg.paths) globs.push(path === '.' ? '**' : `${path}/**`);
    }
    return { kind: 'areas', globs, areas };
  }
  if (scope.startsWith('paths:')) return { kind: 'paths', globs: scope.slice(6).split('|').map((glob) => glob.trim()).filter(Boolean), areas: [] };
  throw new CwError(`Unknown rule scope "${scope}"`);
}

export function buildRulebook(ctx, profile, packs) {
  const byId = collectRules(ctx, profile, packs);
  const disabled = applyCustomizations(ctx, profile, byId);
  const rules = [...byId.values()].sort((a, b) => a.layer - b.layer);
  const groups = new Map();
  const inactive = [];
  for (const rule of rules) {
    const scope = resolveScope(profile, rule.scope);
    rule.globs = scope.globs;
    if (scope.kind === 'areas' && scope.globs.length === 0) {
      inactive.push(rule.id);
      continue;
    }
    let file;
    if (scope.kind === 'global') file = '00-global.md';
    else if (scope.kind === 'areas') file = `area-${[...scope.areas].sort().join('-')}.md`;
    else file = `paths-${rule.pack}-${scope.globs.join('|')}`;
    if (!groups.has(file)) groups.set(file, { file, scope, rules: [] });
    groups.get(file).rules.push(rule);
  }
  // Path groups get stable numbered names per pack.
  const counters = {};
  for (const group of [...groups.values()]) {
    if (!group.file.startsWith('paths-')) continue;
    const pack = group.rules[0].pack;
    counters[pack] = (counters[pack] ?? 0) + 1;
    groups.delete(group.file);
    group.file = `paths-${pack}-${counters[pack]}.md`;
    groups.set(group.file, group);
  }
  const sources = packs.map((pack) => `${pack.id}@${pack.version}${pack.variant ? ` (${pack.variant})` : ''}`).concat(profile.rules.add.length ? ['project'] : []);
  const outputs = [...groups.values()].sort((a, b) => a.file.localeCompare(b.file)).map((group) => ({
    file: group.file,
    content: renderGroup(group, sources, group.file === '00-global.md' ? disabled : []),
  }));
  if (!groups.has('00-global.md')) outputs.unshift({ file: '00-global.md', content: renderGroup({ file: '00-global.md', scope: { kind: 'global', globs: [] }, rules: [] }, sources, disabled) });
  return { rules: rules.filter((rule) => !inactive.includes(rule.id)), outputs, disabled, inactive, packs };
}

const PREAMBLE = `These rules apply to every change in this repository, made by people or agents. They cover new and changed code; don't rewrite untouched code just to comply. Reviewers check every applicable rule and cite its ID in findings. If a rule conflicts with an explicit requirement in the task spec, the spec wins, except for rules marked **protected**, which a spec can't override. State any deviation in the report. \`cw rules applicable --task <id>\` lists the rules that apply to a task's diff.`;

function renderGroup(group, sources, disabled) {
  const isGlobal = group.file === '00-global.md';
  const lines = [];
  if (!isGlobal) {
    lines.push('---', 'paths:');
    for (const glob of group.scope.globs) lines.push(`  - "${glob}"`);
    lines.push('---');
  }
  lines.push(GENERATED_MARKER, `<!-- Sources: ${sources.join(', ')} -->`, '');
  const title = isGlobal ? 'all files' : group.scope.kind === 'areas' ? group.scope.areas.join(', ') : group.scope.globs.join(', ');
  lines.push(`# Workflow rules — ${title}`, '');
  if (isGlobal) lines.push(PREAMBLE, '');
  for (const rule of group.rules) {
    const tags = [rule.severity, rule.protected ? 'protected' : null].filter(Boolean).join(' · ');
    lines.push(`## ${rule.id} — ${rule.title} · ${tags}`, '', rule.body, '');
  }
  if (disabled.length) {
    lines.push('## Disabled in this project', '');
    for (const item of disabled) lines.push(`- ${item.id}: ${item.reason}`);
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

export function lockFor(ctx, book, profileText) {
  return {
    version: 1,
    generator: { plugin: 'dev-workflow', version: pluginVersion() },
    profileHash: sha(profileText),
    packs: book.packs.map((pack) => ({ id: pack.id, version: pack.version, variant: pack.variant, source: pack.source })),
    rules: book.rules.map((rule) => ({
      id: rule.id,
      title: rule.title,
      source: rule.source,
      hash: sha(`${rule.title}\n${rule.severity}\n${rule.scope}\n${rule.body}`),
      aliases: rule.aliases,
      protected: rule.protected,
      severity: rule.severity,
      scope: rule.scope,
      ...(rule.modified ? { modified: rule.modified } : {}),
    })),
    inactive: book.inactive,
    disabled: book.disabled,
    outputs: book.outputs.map((output) => ({ file: `.claude/rules/workflow/${output.file}`, hash: sha(output.content) })),
  };
}

export const rulesOutDir = (ctx) => join(ctx.configRoot ?? ctx.repoRoot, '.claude', 'rules', 'workflow');
export const lockPath = (ctx) => join(ctx.workflowDir, 'rulebook.lock.json');

export function writeRulebook(ctx, book, profileText) {
  const dir = rulesOutDir(ctx);
  const keep = new Set(book.outputs.map((output) => output.file));
  if (existsSync(dir)) {
    for (const file of readdirSync(dir)) {
      if (keep.has(file)) continue;
      const path = join(dir, file);
      if (readFileSync(path, 'utf8').includes(GENERATED_MARKER)) unlinkSync(path);
    }
  }
  for (const output of book.outputs) {
    writeAtomic(join(dir, output.file), output.content);
    if (Buffer.byteLength(output.content) > 12 * 1024) warn(`${output.file} is larger than 12 KB (context cost)`);
  }
  const lock = lockFor(ctx, book, profileText);
  writeJson(lockPath(ctx), lock);
  return lock;
}

export function diffRulebook(ctx, book, profileText) {
  const fresh = lockFor(ctx, book, profileText);
  const old = readJson(lockPath(ctx), null);
  const problems = [];
  if (!old) return { isCurrent: false, problems: ['no rulebook.lock.json yet'] };
  const oldRules = new Map(old.rules.map((rule) => [rule.id, rule]));
  const newRules = new Map(fresh.rules.map((rule) => [rule.id, rule]));
  for (const id of newRules.keys()) if (!oldRules.has(id)) problems.push(`added ${id}`);
  for (const id of oldRules.keys()) if (!newRules.has(id)) problems.push(`removed ${id}`);
  for (const [id, rule] of newRules) if (oldRules.has(id) && oldRules.get(id).hash !== rule.hash) problems.push(`changed ${id}`);
  if (old.generator.version !== fresh.generator.version) problems.push(`plugin ${old.generator.version} → ${fresh.generator.version}`);
  for (const output of book.outputs) {
    const path = join(rulesOutDir(ctx), output.file);
    if (!existsSync(path)) problems.push(`missing ${output.file}`);
    else if (readFileSync(path, 'utf8') !== output.content) problems.push(`${output.file} differs (hand-edited or outdated)`);
  }
  return { isCurrent: problems.length === 0, problems };
}

export function applicableRules(book, files) {
  return book.rules.filter((rule) => rule.globs.length === 0 || files.some((file) => matchAny(file, rule.globs)));
}

export function findRules(book, idOrAlias) {
  const key = idOrAlias.toUpperCase();
  const exact = book.rules.filter((rule) => rule.id === key);
  return exact.length ? exact : book.rules.filter((rule) => rule.aliases.includes(key));
}
