const sha = (text) => `sha256:${createHash('sha256').update(text).digest('hex').slice(0, 16)}`;
const unique = (items) => [...new Set(items)];

// ---- parsing (§7 grammar) ----

// { kind: 'all' } | { kind: 'areas', areas } | { kind: 'paths', globs }; null when malformed.
export function parseScope(scope) {
  if (scope === 'all') return { kind: 'all' };
  const match = /^(areas|paths):(.+)$/.exec(scope);
  if (!match) return null;
  const items = match[2].split(match[1] === 'areas' ? ',' : '|').map((item) => item.trim()).filter(Boolean);
  if (!items.length) return null;
  return match[1] === 'areas' ? { kind: 'areas', areas: unique(items) } : { kind: 'paths', globs: unique(items) };
}

function parseMeta(text, where, problems) {
  const meta = { severity: 'blocking', scope: 'all', protected: false, when: null };
  for (const part of text.split(';').map((item) => item.trim()).filter(Boolean)) {
    const eq = part.indexOf('=');
    const key = (eq === -1 ? part : part.slice(0, eq)).trim();
    const value = eq === -1 ? '' : part.slice(eq + 1).trim();
    if (!META_KEYS.includes(key)) {
      problems.push(`${where}: unknown meta key "${key}" (allowed: ${META_KEYS.join(', ')})`);
    } else if (key === 'severity') {
      if (['blocking', 'advisory'].includes(value)) meta.severity = value;
      else problems.push(`${where}: severity must be blocking or advisory (got "${value}")`);
    } else if (key === 'protected') {
      if (['true', 'false'].includes(value)) meta.protected = value === 'true';
      else problems.push(`${where}: protected must be true or false (got "${value}")`);
    } else if (key === 'scope') {
      if (parseScope(value)) meta.scope = value;
      else problems.push(`${where}: scope must be all, areas:<a,b> or paths:<glob|glob> (got "${value}")`);
    } else {
      const when = /^option:([A-Za-z][A-Za-z0-9_]*)(?:=(.+))?$/.exec(value);
      if (when) meta.when = { option: when[1], value: when[2] ?? null };
      else problems.push(`${where}: when must be option:<name> or option:<name>=<value> (got "${value}")`);
    }
  }
  return meta;
}

// Rules of one file: [{ id, title, severity, scope, protected, when, body, file, line }]. Frontmatter
// and text before the first heading are ignored. Every problem is collected; then one error (exit 1).
export function parseRuleFile(text, file) {
  const lines = String(text).replace(/^﻿/, '').replace(/\r\n/g, '\n').split('\n');
  let start = 0;
  if (lines[0] === '---') {
    const end = lines.indexOf('---', 1);
    if (end !== -1) start = end + 1;
  }
  const rules = [];
  const problems = [];
  let current = null;
  const finish = () => {
    if (!current) return;
    current.body = current.lines.join('\n').trim();
    delete current.lines;
    if (!current.body) problems.push(`${file}:${current.line}: rule ${current.id} has an empty body. Write the rule text under its meta line`);
    rules.push(current);
    current = null;
  };
  for (let i = start; i < lines.length; i += 1) {
    const line = lines[i];
    if (!line.startsWith('## ')) {
      current?.lines.push(line);
      continue;
    }
    finish();
    const heading = HEADING.exec(line.trimEnd());
    if (!heading) {
      problems.push(`${file}:${i + 1}: "${line.trim()}" is not a rule heading. Use "## RULE-ID — Title" or remove the line`);
      continue;
    }
    const [, id, title] = heading;
    if (rules.some((rule) => rule.id === id)) problems.push(`${file}:${i + 1}: rule ${id} appears twice in this file. Remove one`);
    const meta = META.exec((lines[i + 1] ?? '').trim());
    if (!meta) {
      problems.push(`${file}:${i + 1}: rule ${id} has no "<!-- rule: … -->" line under its heading. Add one, e.g. <!-- rule: severity=blocking; scope=all -->`);
    }
    current = { id, title: title.trim(), ...parseMeta(meta ? meta[1] : '', `${file}:${i + 2}`, problems), file, line: i + 1, lines: [] };
    if (meta) i += 1;
  }
  finish();
  if (problems.length) {
    throw failedError(`Rule file ${file} is invalid:\n${problems.map((problem) => `- ${problem}`).join('\n')}`, 'Correct the rule file as each line says.', { problems });
  }
  return rules;
}

// ---- building ----

const displayPath = (ws, path) => (path.startsWith(packsDir) ? relative(packsDir, path) : relative(ws.configRoot, path));
const where = (rule) => `${rule.file}:${rule.line}`;

function readRules(ws, path, problems) {
  try {
    return parseRuleFile(readFileSync(path, 'utf8'), displayPath(ws, path));
  } catch (error) {
    if (error.details?.problems) problems.push(...error.details.problems);
    else problems.push(`${displayPath(ws, path)}: ${error.message}`);
    return [];
  }
}

// Every .claude/dev-workflow/rules/*.md (name order), then the rules.add files not already among them.
function projectRuleFiles(ws) {
  const dir = join(ws.configRoot, PROJECT_RULES_DIR);
  const paths = existsSync(dir) ? readdirSync(dir).filter((name) => name.endsWith('.md')).sort().map((name) => join(dir, name)) : [];
  for (const file of ws.config.rules.add) {
    const path = resolve(ws.configRoot, file);
    if (!paths.includes(path)) paths.push(path);
  }
  return paths;
}

const isOn = (value) => (Array.isArray(value) ? value.length > 0 : Boolean(value));
const shown = (value) => (Array.isArray(value) ? value.join(', ') : String(value));

// Pack rules with when=option:… are inactive unless the pack option matches (case-insensitive).
function applyConditions(rules, problems) {
  for (const rule of rules) {
    if (!rule.when) continue;
    const { option, value } = rule.when;
    if (!rule.packRef) {
      problems.push(`${where(rule)}: ${rule.id}: project rules have no pack options, so when=option:${option} cannot apply; remove it`);
      continue;
    }
    const specs = rule.packRef.manifest.options ?? {};
    if (!(option in specs)) {
      problems.push(`${where(rule)}: when=option:${option} is not an option of pack ${rule.pack} (options: ${Object.keys(specs).join(', ') || 'none'})`);
      continue;
    }
    const actual = rule.packRef.options[option];
    const matches = value === null ? isOn(actual) : String(actual).toLowerCase() === value.toLowerCase();
    if (!matches) rule.inactive = value === null ? `option ${option} is off` : `option ${option} is ${shown(actual)} (needs ${value})`;
  }
}

// add → override → extend → disable (§7 layering 3); options names are checked too.
function applyCustomizations(ws, byId, problems, warnings, inputs) {
  const custom = ws.config.rules;
  const allowProtected = custom.allowProtected === true;
  const known = (section, id) => {
    const rule = byId.get(id);
    if (!rule) {
      problems.push(`rules.${section}: unknown rule ${id}. Check the ID with: cw rules list`);
      return null;
    }
    if (rule.inactive) {
      warnings.push(`rules.${section}.${id} has no effect: ${id} is inactive (${rule.inactive})`);
      return null;
    }
    return rule;
  };
  const protectedProblem = (section, id) => `rules.${section}: ${id} is protected. Set rules.allowProtected to true and give a reason, or keep the rule`;

  for (const [id, { file, reason }] of Object.entries(custom.override)) {
    const rule = known('override', id);
    if (!rule) continue;
    if (rule.protected && !(allowProtected && reason?.trim())) {
      problems.push(protectedProblem('override', id));
      continue;
    }
    const path = resolve(ws.configRoot, file);
    inputs.add(path);
    if (!existsSync(path)) {
      problems.push(`rules.override.${id}: ${file} does not exist. Create it (relative to ${ws.configRoot}) or fix the path`);
      continue;
    }
    const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n').replace(/^---\n[\s\S]*?\n---\n/, '');
    const firstLine = text.split('\n').find((line) => line.trim()) ?? '';
    if (firstLine.startsWith('## ')) {
      const parsed = readRules(ws, path, problems);
      if (parsed.length !== 1 || parsed[0].id !== id) {
        if (parsed.length) problems.push(`rules.override.${id}: ${file} must hold exactly one rule, ${id}`);
        continue;
      }
      const [replacement] = parsed;
      // A protected rule stays protected whatever the override says.
      Object.assign(rule, { title: replacement.title, severity: replacement.severity, scope: replacement.scope, protected: rule.protected || replacement.protected, body: replacement.body });
    } else {
      rule.body = text.trim();
    }
    rule.modified = 'override';
    if (rule.protected) warnings.push(`protected rule ${id} is overridden by ${file}: ${reason}`);
  }

  for (const [id, text] of Object.entries(custom.extend)) {
    const rule = known('extend', id);
    if (!rule) continue;
    rule.body = `${rule.body}\n\n**Project addition:** ${text.trim()}`;
    rule.modified = rule.modified === 'override' ? 'override+extend' : 'extend';
  }

  const disabled = [];
  for (const { id, reason } of custom.disable) {
    const rule = known('disable', id);
    if (!rule) continue;
    if (!reason?.trim()) {
      problems.push(`rules.disable: ${id} needs a reason`);
      continue;
    }
    if (rule.protected && !allowProtected) {
      problems.push(protectedProblem('disable', id));
      continue;
    }
    if (rule.protected) warnings.push(`protected rule ${id} is disabled: ${reason}`);
    rule.disabled = reason;
    disabled.push({ id, reason });
  }

  for (const id of Object.keys(custom.options)) known('options', id);
  return disabled;
}

function placeholderProblem(rule, token) {
  const [, namespace, path] = /^\{(\w+)\.(.+)\}$/.exec(token);
  const at = `${rule.source}/${rule.id}: unresolved placeholder ${token}`;
  if (namespace === 'options' && !rule.packRef) return `${where(rule)}: ${rule.id}: project rules have no pack options; replace ${token} with {ruleOptions.${path}}`;
  if (namespace === 'options') return `${at}. Set packs[${rule.pack}].options.${path} in ${CONFIG_FILE}`;
  if (namespace === 'ruleOptions') return `${at}. Set rules.options.${rule.id}.${path} in ${CONFIG_FILE}`;
  if (PROJECT_PLACEHOLDERS.includes(path)) return `${at}. Set project.${path} in ${CONFIG_FILE}`;
  return `${at}. The project placeholders are ${PROJECT_PLACEHOLDERS.map((key) => `{project.${key}}`).join(', ')}; correct the rule text`;
}

// A project pack that shadows a bundled pack keeps the bundled pack's protected rules (§7): such a
// rule stays protected in the shadow, and dropping it needs rules.allowProtected, like disabling it.
function keepBundledProtection(ws, pack, byId, { problems, warnings, inputs }) {
  const root = join(packsDir, pack.id);
  const manifest = readPackManifest(root);
  const bundled = { root, manifest, variant: manifest.variants?.[pack.variant] ? pack.variant : null };
  const shadow = `project pack ${pack.id} (${join(PROJECT_PACKS_DIR, pack.id)})`;
  for (const { path } of packRuleFiles(bundled)) {
    inputs.add(path);
    for (const { id } of readRules(ws, path, problems).filter((rule) => rule.protected)) {
      const rule = byId.get(id);
      if (rule?.pack === pack.id) rule.protected = true;
      else if (ws.config.rules.allowProtected === true) warnings.push(`${shadow} drops the protected rule ${id} of the bundled pack ${pack.id}`);
      else problems.push(`${shadow} drops the protected rule ${id} of the bundled pack ${pack.id}. Keep ${id} in the project pack, or set rules.allowProtected to true`);
    }
  }
}

// Resolves globs: areas → one glob per package with the area; paths globs are validated and normalized
// (a ./ prefix would become app/./… after prefixing); outputGlobs carry the appRoot prefix in in-place
// mode (§5 Generated output), globs stay relative to the work repo for applicable and drift.
function applyScope(ws, rule, problems, warnings) {
  const scope = parseScope(rule.scope);
  if (!scope) {
    problems.push(`${where(rule)}: ${rule.id}: scope must be all, areas:<a,b> or paths:<glob|glob> (got "${rule.scope}")`);
    return;
  }
  rule.scopeKind = scope.kind;
  rule.areas = scope.kind === 'areas' ? scope.areas : [];
  if (scope.kind === 'all') rule.globs = [];
  else if (scope.kind === 'paths') {
    for (const glob of scope.globs) {
      const error = globError(glob);
      // A scope glob ends up in the paths: of a .claude/rules file, where Claude Code reads an unclosed
      // [ as an invalid pattern that matches nothing (code.claude.com/docs/en/memory, read 2026-10-19).
      const note = error === UNCLOSED_CLASS ? ' (Claude Code ignores such a pattern in the paths of .claude/rules)' : '';
      if (error) problems.push(`${glob} in ${rule.id}: ${error}${note}`);
    }
    rule.globs = unique(scope.globs.map(normalizeGlob));
  } else {
    const packages = ws.config.packages.filter((pkg) => pkg.areas.some((area) => scope.areas.includes(area)));
    rule.globs = unique(packages.map((pkg) => (pkg.path === '.' ? '**/*' : `${pkg.path}/**/*`)));
    if (!rule.globs.length) {
      rule.inactive = `no package has area ${scope.areas.join(' or ')}`;
      warnings.push(`${rule.id} is inactive: ${rule.inactive}`);
    }
  }
  const prefix = ws.config.workspace.mode === 'in-place' ? `${ws.config.workspace.appRoot}/` : '';
  rule.outputGlobs = rule.globs.map((glob) => `${prefix}${glob}`);
}

function renderOutput({ name, title, globs, rules }, { sources, disabled }) {
  const isGlobal = name === '00-global.md';
  const lines = [];
  if (globs.length) lines.push('---', 'paths:', ...globs.map((glob) => `  - ${JSON.stringify(glob)}`), '---');
  lines.push(MARKER, `<!-- Sources: ${sources.join(', ')} -->`, '', `# dev-workflow rules: ${title}`, '');
  if (isGlobal) lines.push(PREAMBLE, '');
  for (const rule of rules) {
    const tags = [rule.severity, rule.protected ? 'protected' : null].filter(Boolean).join(' · ');
    lines.push(`## ${rule.id} — ${rule.title} · ${tags}`, '', rule.body, '');
  }
  if (isGlobal && disabled.length) {
    lines.push('## Disabled in this project', '', ...disabled.map((item) => `- ${item.id}: ${item.reason}`), '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

// Groups active rules into 00-global.md, area-<a+b>.md (one per area set; area names can't contain
// +, so two sets never share a file) and paths-<pack>-<n>.md (one per glob list, numbered per pack in
// layer order). Rules keep layer order inside a file.
function planOutputs(ws, rules) {
  const inPlace = ws.config.workspace.mode === 'in-place';
  const global = { name: '00-global.md', title: 'all files', globs: inPlace ? [`${ws.config.workspace.appRoot}/**`] : [], rules: [] };
  const groups = new Map([['global', global]]);
  const counters = {};
  for (const rule of rules) {
    let key = 'global';
    if (rule.scopeKind === 'areas') {
      const areas = [...rule.areas].sort();
      key = `areas:${areas.join(',')}`;
      if (!groups.has(key)) groups.set(key, { name: `area-${areas.join('+')}.md`, title: areas.join(', '), globs: rule.outputGlobs, rules: [] });
    } else if (rule.scopeKind === 'paths') {
      key = `paths:${rule.outputGlobs.join('|')}`;
      if (!groups.has(key)) {
        counters[rule.pack] = (counters[rule.pack] ?? 0) + 1;
        groups.set(key, { name: `paths-${rule.pack}-${counters[rule.pack]}.md`, title: rule.outputGlobs.join(', '), globs: rule.outputGlobs, rules: [] });
      }
    }
    groups.get(key).rules.push(rule);
    rule.output = groups.get(key).name;
  }
  return [...groups.values()].sort((a, b) => a.name.localeCompare(b.name));
}

// Builds the rulebook in memory (no writes). ws needs { configRoot, config } with a normalized
// config; packs default to resolvePacks(ws). Build errors are aggregated into one error (exit 1).
export function buildRulebook(ws, packs) {
  const warnings = [];
  const resolvedPacks = packs ?? resolvePacks(ws, { onWarning: (warning) => warnings.push(warning) });
  const problems = [];
  // Files and directories read, for an mtime cache (D11); the rules directory's mtime changes when a file is added.
  const inputs = new Set([...resolvedPacks.flatMap((pack) => pack.files ?? []), join(ws.configRoot, PROJECT_RULES_DIR)]);
  const rules = [];
  const byId = new Map();
  const addRule = (rule) => {
    const existing = byId.get(rule.id);
    if (!existing) {
      rules.push(rule);
      byId.set(rule.id, rule);
    } else if (rule.fromVariant && existing.pack === rule.pack && !existing.fromVariant) {
      // A variant file may redefine a base rule of its own pack; it keeps the base rule's position.
      rules[rules.indexOf(existing)] = rule;
      byId.set(rule.id, rule);
    } else {
      problems.push(`Duplicate rule ID ${rule.id} in ${where(existing)} and ${where(rule)}. Rename the project rule (use a project prefix) or remove one`);
    }
  };

  resolvedPacks.forEach((pack, layer) => {
    for (const { path, isVariant } of packRuleFiles(pack)) {
      inputs.add(path);
      for (const rule of readRules(ws, path, problems)) {
        addRule({ ...rule, pack: pack.id, packRef: pack, source: isVariant ? `${pack.id}@${pack.variant}` : pack.id, layer, fromVariant: isVariant });
      }
    }
  });

  const packPrefixes = new Set(rules.map((rule) => rule.id.split('-')[0]));
  const projectFiles = projectRuleFiles(ws);
  for (const path of projectFiles) {
    inputs.add(path);
    if (!existsSync(path)) {
      problems.push(`rules.add: ${relative(ws.configRoot, path)} does not exist. Fix the path (relative to ${ws.configRoot}) or remove the entry`);
      continue;
    }
    for (const rule of readRules(ws, path, problems)) {
      const prefix = rule.id.split('-')[0];
      if (packPrefixes.has(prefix)) warnings.push(`project rule ${rule.id} (${where(rule)}) uses the pack prefix ${prefix}; give project rules a project prefix`);
      addRule({ ...rule, pack: 'project', packRef: null, source: 'project', layer: resolvedPacks.length, fromVariant: false });
    }
  }

  for (const pack of resolvedPacks.filter((candidate) => candidate.shadows)) keepBundledProtection(ws, pack, byId, { problems, warnings, inputs });
  applyConditions(rules, problems);
  const disabled = applyCustomizations(ws, byId, problems, warnings, inputs);

  for (const rule of rules) {
    if (rule.inactive || rule.disabled) continue;
    const values = { options: rule.packRef?.options ?? {}, ruleOptions: ws.config.rules.options[rule.id] ?? {}, project: ws.config.project };
    for (const field of ['title', 'scope', 'body']) {
      const { text, unresolved, invalid } = resolvePlaceholders(rule[field], values);
      rule[field] = text;
      problems.push(...unresolved.map((token) => placeholderProblem(rule, token)));
      problems.push(...invalid.map((token) => `${rule.source}/${rule.id}: ${invalidPlaceholder(token)}`));
    }
    applyScope(ws, rule, problems, warnings);
  }

  if (problems.length) {
    throw failedError(
      `Rulebook build failed:\n${problems.map((problem) => `- ${problem}`).join('\n')}`,
      `Correct the named rule files or the rules section of ${CONFIG_FILE}, then run cw rules build again.`,
      { problems },
    );
  }

  const active = rules.filter((rule) => !rule.inactive && !rule.disabled);
  const hasProjectLayer = projectFiles.length > 0 || ['override', 'extend', 'options'].some((key) => Object.keys(ws.config.rules[key]).length) || disabled.length > 0;
  const sources = [...resolvedPacks.map((pack) => (pack.variant ? `${pack.id} (${pack.variant})` : pack.id)), ...(hasProjectLayer ? ['project'] : [])];
  const outputs = planOutputs(ws, active).map((group) => ({ file: group.name, content: renderOutput(group, { sources, disabled }) }));
  for (const output of outputs) {
    if (Buffer.byteLength(output.content) > SIZE_WARNING_BYTES) warnings.push(`${OUT_DIR}/${output.file} is larger than 12 KB, which costs context; scope or disable rules to shrink it`);
  }
  return {
    rules: active.map(({ packRef, fromVariant, ...rule }) => rule),
    inactive: rules.filter((rule) => rule.inactive && !rule.disabled).map((rule) => ({ id: rule.id, reason: rule.inactive })),
    disabled,
    outputs,
    warnings,
    packs: resolvedPacks,
    inputs: [...inputs],
  };
}


// ---- queries ----

// { rule } | { disabled: { id, reason } } | { inactive: { id, reason } } | null.
export function findRule(book, id) {
  const rule = book.rules.find((candidate) => candidate.id === id);
  if (rule) return { rule };
  const disabled = book.disabled.find((item) => item.id === id);
  if (disabled) return { disabled };
  const inactive = book.inactive.find((item) => item.id === id);
  return inactive ? { inactive } : null;
}

export const ruleIdPrefixes = (book) => new Set(book.rules.map((rule) => rule.id.split('-')[0]));

// Every global rule, plus each scoped rule whose globs match a file or whose areas include one of
// areas; in layer order. files are relative to the work tree.
export const applicableRules = (book, { files = [], areas = [] } = {}) =>
  book.rules.filter((rule) => rule.globs.length === 0 || files.some((file) => matchAny(file, rule.globs)) || rule.areas.some((area) => areas.includes(area)));

// What `cw rules applicable --task` prints and `review save` checks rulesChecked against: the task's
// work tree and base come from task.json, never from the cwd (D5).
export function applicableForTask(ws, task, book = buildRulebook(ws)) {
  const workTree = workTreeOf(ws, task);
  if (!workTree) throw preconditionError(`Task ${task.id} has no work tree yet.`, `Run cw ws setup --task ${task.id} first.`);
  if (!existsSync(workTree)) throw preconditionError(`The work tree ${workTree} of task ${task.id} is missing.`, `Run cw ws setup --task ${task.id}, or check the task with cw task show --task ${task.id}.`);
  const base = task.base?.commit ?? null;
  const files = changedFiles(workTree, base);
  return { task: task.id, workTree, base, files, rules: applicableRules(book, { files, areas: task.areas ?? [] }) };
}

