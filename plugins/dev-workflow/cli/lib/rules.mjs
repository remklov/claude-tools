const ruleHash = (rule) => sha(`${rule.title}\n${rule.severity}\n${rule.scope}\n${rule.protected}\n${rule.body}`);

export function lockFor(book) {
  return {
    version: 1,
    generator: { plugin: 'dev-workflow', version: pluginVersion() },
    packs: book.packs.map((pack) => ({ id: pack.id, version: pack.version, variant: pack.variant, source: pack.source })),
    rules: book.rules.map((rule) => ({
      id: rule.id,
      title: rule.title,
      source: rule.source,
      severity: rule.severity,
      scope: rule.scope,
      protected: rule.protected,
      hash: ruleHash(rule),
      ...(rule.modified ? { modified: rule.modified } : {}),
    })),
    inactive: book.inactive,
    disabled: book.disabled,
    outputs: book.outputs.map((output) => ({ file: `${OUT_DIR}/${output.file}`, hash: sha(output.content) })),
  };
}

// Top-level .md files of the output dir that carry the marker.
function markedFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((name) => name.endsWith('.md') && (readText(join(dir, name)) ?? '').includes(MARKER_PREFIX)).sort();
}

// Writes the outputs (unchanged files are left alone), deletes stale marked files and writes the lock.
export function writeRulebook(ws, book) {
  const dir = join(ws.configRoot, OUT_DIR);
  for (const output of book.outputs) {
    const text = readText(join(dir, output.file));
    if (text !== null && !text.includes(MARKER_PREFIX)) {
      throw failedError(`${OUT_DIR}/${output.file} exists and was not generated by cw.`, `Move or delete ${OUT_DIR}/${output.file}, then run cw rules build.`);
    }
  }
  const lock = lockFor(book);
  const expected = new Set(book.outputs.map((output) => output.file));
  const deleted = [];
  try {
    for (const output of book.outputs) {
      if (readText(join(dir, output.file)) !== output.content) writeAtomic(join(dir, output.file), output.content);
    }
    for (const name of markedFiles(dir)) {
      if (expected.has(name)) continue;
      unlinkSync(join(dir, name));
      deleted.push(`${OUT_DIR}/${name}`);
    }
    writeJson(join(ws.configRoot, LOCK_FILE), lock);
  } catch (error) {
    if (error.code !== 'EPERM' && error.code !== 'EACCES') throw error;
    throw preconditionError(`The sandbox refused writing ${error.path ? relative(ws.configRoot, error.path) : 'the rulebook'} (${error.code}).`, 'Run cw rules build in a terminal.');
  }
  return { lock, files: book.outputs.map((output) => `${OUT_DIR}/${output.file}`), deleted };
}

// Compares a fresh in-memory build with the lock and the files on disk; never writes. A plugin or
// pack version change alone is a note, not drift (§7 Decided in P2).
export function checkRulebook(ws, book) {
  const fresh = lockFor(book);
  const problems = [];
  const notes = [];
  const add = (kind, message, extra = {}) => problems.push({ kind, ...extra, message });
  let old = null;
  try {
    old = readJson(join(ws.configRoot, LOCK_FILE), null);
  } catch {
    add('no-lock', `${LOCK_FILE} is not valid JSON`, { file: LOCK_FILE });
  }
  if (!old && !problems.length) add('no-lock', `no ${LOCK_FILE} yet`, { file: LOCK_FILE });
  if (old) {
    const before = new Map((old.rules ?? []).map((rule) => [rule.id, rule]));
    const after = new Map(fresh.rules.map((rule) => [rule.id, rule]));
    for (const id of after.keys()) if (!before.has(id)) add('added', `added ${id}`, { id });
    for (const id of before.keys()) if (!after.has(id)) add('removed', `removed ${id}`, { id });
    for (const [id, rule] of after) if (before.has(id) && before.get(id).hash !== rule.hash) add('changed', `changed ${id}`, { id });
    if (old.generator?.version !== fresh.generator.version) notes.push(`dev-workflow ${old.generator?.version ?? '?'} → ${fresh.generator.version}`);
    for (const pack of fresh.packs) {
      const previous = (old.packs ?? []).find((candidate) => candidate.id === pack.id);
      if (previous && previous.version !== pack.version) notes.push(`pack ${pack.id} ${previous.version} → ${pack.version}`);
    }
  }
  const lockedHashes = new Map((old?.outputs ?? []).map((output) => [output.file, output.hash]));
  const dir = join(ws.configRoot, OUT_DIR);
  const ruleChanges = problems.length;
  const outdated = [];
  for (const output of book.outputs) {
    const file = `${OUT_DIR}/${output.file}`;
    const text = readText(join(dir, output.file));
    if (text === null) add('missing', `missing ${file}`, { file });
    else if (text !== output.content) {
      // As generated last time (hash in the lock) means the inputs changed; anything else is a hand edit.
      if (!old || lockedHashes.get(file) === sha(text)) outdated.push(file);
      else add('hand-edited', `${file} was edited by hand`, { file });
    }
  }
  // Changed rules explain outdated files already; on their own (a new package path, a new plugin
  // text) outdated files are the only sign of drift.
  if (!ruleChanges) for (const file of outdated) add('outdated', `${file} is out of date`, { file });
  const expected = new Set(book.outputs.map((output) => output.file));
  for (const name of markedFiles(dir)) {
    if (!expected.has(name)) add('stale', `stale ${OUT_DIR}/${name} (no longer generated)`, { file: `${OUT_DIR}/${name}` });
  }
  return { isCurrent: problems.length === 0, problems, notes };
}
